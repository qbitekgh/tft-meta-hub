CREATE TABLE trait
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    set_number INTEGER      NOT NULL,
    api_name   VARCHAR(100) NOT NULL,
    name       VARCHAR(100) NOT NULL,
    icon_url   VARCHAR(500),
    CONSTRAINT uq_trait_set_api_name UNIQUE (set_number, api_name)
);

CREATE TABLE trait_breakpoint
(
    trait_id   BIGINT  NOT NULL REFERENCES trait (id) ON DELETE CASCADE,
    sort_order INTEGER NOT NULL,
    min_units  INTEGER NOT NULL,
    PRIMARY KEY (trait_id, sort_order)
);

CREATE TABLE champion
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    set_number INTEGER      NOT NULL,
    api_name   VARCHAR(100) NOT NULL,
    name       VARCHAR(100) NOT NULL,
    cost       INTEGER      NOT NULL CHECK (cost BETWEEN 1 AND 5),
    icon_url   VARCHAR(500),
    CONSTRAINT uq_champion_set_api_name UNIQUE (set_number, api_name)
);

CREATE TABLE champion_trait
(
    champion_id BIGINT NOT NULL REFERENCES champion (id) ON DELETE CASCADE,
    trait_id    BIGINT NOT NULL REFERENCES trait (id) ON DELETE CASCADE,
    PRIMARY KEY (champion_id, trait_id)
);

CREATE INDEX ix_champion_trait_trait_id ON champion_trait (trait_id);

CREATE TABLE item
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    set_number INTEGER      NOT NULL,
    api_name   VARCHAR(100) NOT NULL,
    name       VARCHAR(100) NOT NULL,
    icon_url   VARCHAR(500),
    category   VARCHAR(20)  NOT NULL
        CHECK (category IN ('COMPONENT', 'COMPLETED', 'EMBLEM', 'RADIANT', 'ARTIFACT')),
    CONSTRAINT uq_item_set_api_name UNIQUE (set_number, api_name)
);
