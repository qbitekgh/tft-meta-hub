-- Game patches entered by the admin. Riot no longer sends a patch number in match data,
-- so a match belongs to the patch with the latest start time before the game.
CREATE TABLE game_patch
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patch      VARCHAR(10)              NOT NULL UNIQUE,
    set_number INTEGER                  NOT NULL,
    starts_at  TIMESTAMP WITH TIME ZONE NOT NULL UNIQUE
);

-- Collector state. The only table with PUUIDs; they are never shown in the UI.
CREATE TABLE tracked_player
(
    puuid                  VARCHAR(100)             PRIMARY KEY,
    platform               VARCHAR(10)              NOT NULL,
    last_seen_on_ladder_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_fetched_at        TIMESTAMP WITH TIME ZONE
);

CREATE TABLE tft_match
(
    id            VARCHAR(30) PRIMARY KEY,
    platform      VARCHAR(10)              NOT NULL,
    game_datetime TIMESTAMP WITH TIME ZONE NOT NULL,
    game_version  VARCHAR(100),
    patch         VARCHAR(10),
    set_number    INTEGER                  NOT NULL,
    collected_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_tft_match_game_datetime ON tft_match (game_datetime);
CREATE INDEX ix_tft_match_patch ON tft_match (patch);

-- One board of one player in one match. No player identity is stored.
CREATE TABLE participant
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id  VARCHAR(30) NOT NULL REFERENCES tft_match (id) ON DELETE CASCADE,
    placement INTEGER     NOT NULL CHECK (placement BETWEEN 1 AND 8),
    level     INTEGER     NOT NULL
);

CREATE INDEX ix_participant_match_id ON participant (match_id);

CREATE TABLE participant_unit
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id BIGINT       NOT NULL REFERENCES participant (id) ON DELETE CASCADE,
    slot           INTEGER      NOT NULL,
    character_id   VARCHAR(100) NOT NULL,
    star_level     INTEGER      NOT NULL CHECK (star_level BETWEEN 1 AND 4)
);

CREATE INDEX ix_participant_unit_participant_id ON participant_unit (participant_id);

CREATE TABLE participant_unit_item
(
    unit_id   BIGINT       NOT NULL REFERENCES participant_unit (id) ON DELETE CASCADE,
    slot      INTEGER      NOT NULL,
    item_name VARCHAR(100) NOT NULL,
    PRIMARY KEY (unit_id, slot)
);

-- Only active traits are stored.
CREATE TABLE participant_trait
(
    participant_id BIGINT       NOT NULL REFERENCES participant (id) ON DELETE CASCADE,
    name           VARCHAR(100) NOT NULL,
    num_units      INTEGER      NOT NULL,
    tier_current   INTEGER      NOT NULL,
    style          INTEGER      NOT NULL
);

CREATE INDEX ix_participant_trait_participant_id ON participant_trait (participant_id);

CREATE TABLE collection_run
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_trigger     VARCHAR(20)              NOT NULL CHECK (run_trigger IN ('MANUAL', 'SCHEDULED')),
    status          VARCHAR(20)              NOT NULL
        CHECK (status IN ('RUNNING', 'SUCCEEDED', 'KEY_INVALID', 'FAILED')),
    started_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at     TIMESTAMP WITH TIME ZONE,
    players_checked INTEGER                  NOT NULL DEFAULT 0,
    matches_saved   INTEGER                  NOT NULL DEFAULT 0,
    matches_skipped INTEGER                  NOT NULL DEFAULT 0,
    error_message   VARCHAR(500)
);
