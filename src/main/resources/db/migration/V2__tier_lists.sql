CREATE TABLE tier_list
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(100) NOT NULL,
    patch        VARCHAR(10)  NOT NULL,
    set_number   INTEGER      NOT NULL,
    status       VARCHAR(20)  NOT NULL CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    published_at TIMESTAMP WITH TIME ZONE,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

-- At most one tier list can be published at a time (a partial unique index covers only PUBLISHED rows).
CREATE UNIQUE INDEX uq_tier_list_single_published ON tier_list (status) WHERE status = 'PUBLISHED';

CREATE TABLE composition
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tier_list_id BIGINT       NOT NULL REFERENCES tier_list (id) ON DELETE CASCADE,
    name         VARCHAR(100) NOT NULL,
    tier         VARCHAR(20)  NOT NULL CHECK (tier IN ('S', 'A', 'B', 'C', 'SITUATIONAL')),
    position     INTEGER      NOT NULL CHECK (position >= 1),
    play_style   VARCHAR(20)  NOT NULL
        CHECK (play_style IN ('FAST_8', 'REROLL_1_COST', 'REROLL_2_COST', 'REROLL_3_COST', 'FLEX')),
    difficulty   VARCHAR(10)  NOT NULL CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    tips         VARCHAR(2000)
);

CREATE INDEX ix_composition_tier_list_id ON composition (tier_list_id);

CREATE TABLE composition_unit
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    composition_id BIGINT  NOT NULL REFERENCES composition (id) ON DELETE CASCADE,
    champion_id    BIGINT  NOT NULL REFERENCES champion (id),
    slot           INTEGER NOT NULL,
    carry          BOOLEAN NOT NULL,
    star_level     INTEGER NOT NULL CHECK (star_level BETWEEN 1 AND 3)
);

CREATE INDEX ix_composition_unit_composition_id ON composition_unit (composition_id);

CREATE TABLE composition_unit_item
(
    unit_id    BIGINT  NOT NULL REFERENCES composition_unit (id) ON DELETE CASCADE,
    sort_order INTEGER NOT NULL CHECK (sort_order BETWEEN 0 AND 2),
    item_id    BIGINT  NOT NULL REFERENCES item (id),
    PRIMARY KEY (unit_id, sort_order)
);
